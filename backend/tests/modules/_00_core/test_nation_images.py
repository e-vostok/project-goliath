    async def test_oversized_body_is_413(self, client, test_db_session):
        """A body over images.max_upload_bytes is cut: a Content-Length
        already over the limit is rejected before the body is read."""
        player = await seed_player(test_db_session)
        await seed_nation(test_db_session, player)
        headers = bearer_headers(player.id)
        limit = IMAGES.max_upload_bytes

        resp = await client.put(
            "/api/v1/nations/me/images/flag",
            headers=headers,
            content=b"\x00" * (limit + 1),
        )
        assert resp.status_code == 413
        assert resp.json()["code"] == "IMAGE_TOO_LARGE"

        # Exactly the limit still fails only later (type check -> 415).
        at_limit = await client.put(
            "/api/v1/nations/me/images/flag",
            headers=headers,
            content=b"\x00" * limit,
        )
        assert at_limit.status_code == 415
        assert at_limit.json()["code"] == "IMAGE_UNSUPPORTED"

