    async def test_two_nations_same_file_independent_urls(
        self, client, test_db_session
    ):
        """Two nations uploading the same file get two rows with one
        sha256; one nation's replacement does not kill the other's
        URL (the shared hash stays served)."""
        first_player = await seed_player(test_db_session, vk_user_id=111)
        second_player = await seed_player(test_db_session, vk_user_id=222)
        first = await seed_nation(
            test_db_session, first_player, name="First Realm", short_name="FR1"
        )
        second = await seed_nation(
            test_db_session,
            second_player,
            name="Second Realm",
            color_hex="#334455",
            short_name="SR2",
        )
        same_file = _png((1200, 800))

        up_first = await client.put(
            "/api/v1/nations/me/images/flag",
            headers=bearer_headers(first_player.id),
            content=same_file,
        )
        up_second = await client.put(
            "/api/v1/nations/me/images/flag",
            headers=bearer_headers(second_player.id),
            content=same_file,
        )
        assert up_first.status_code == 200 and up_second.status_code == 200
        shared_url = up_first.json()["url"]
        assert up_second.json()["url"] == shared_url
        assert len(
            await _rows(test_db_session, first.id, "flag")
        ) == 1
        assert len(
            await _rows(test_db_session, second.id, "flag")
        ) == 1

        replaced = await client.put(
            "/api/v1/nations/me/images/flag",
            headers=bearer_headers(first_player.id),
            content=_png((1500, 1000), color=(90, 90, 90)),
        )
        assert replaced.status_code == 200
        # The shared hash survives through the second nation's row.
        assert (await client.get(shared_url)).status_code == 200

