        await seed_nation(test_db_session, player)
        resp = await client.put(
            "/api/v1/nations/me/images/flag",
            headers=bearer_headers(player.id),
            content=_png((1200, 800)),
        )
        assert resp.status_code == 200
        sha = _webp_sha_of(resp.json())

        for path in (
            f"/api/v1/images/{'0' * 64}/full",  # unknown hash
            f"/api/v1/images/{sha}/medium",  # bad variant
            f"/api/v1/images/{sha[:-1]}/full",  # 63 chars
            f"/api/v1/images/{sha.upper()}/full",  # not lowercase hex
            "/api/v1/images/zz/full",  # malformed hash
        ):
            res = await client.get(path)
            assert res.status_code == 404, path
            assert res.headers["cache-control"] == "no-store", path


