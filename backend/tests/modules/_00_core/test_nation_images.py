    async def test_concurrent_replaces_end_with_one_row(self, tmp_path):
        """Two overlapping replaces of the same kind end with exactly
        one row and no error (the unique key + one retry absorb the
        race) — file-backed SQLite so two real sessions can race."""
        engine = create_async_engine(
            f"sqlite+aiosqlite:///{(tmp_path / 'race.db').as_posix()}"
        )
        try:
            async with engine.begin() as conn:
                await conn.run_sync(Base.metadata.create_all)
            maker = async_sessionmaker(
                engine, class_=AsyncSession, expire_on_commit=False
            )
            async with maker() as session:
                player = await seed_player(session)
                nation = await seed_nation(session, player)
                await session.commit()
                nation_id, player_id = nation.id, player.id

            first = ProcessedImage(
                full=b"f1", thumb=b"t1", sha256="11" * 32, byte_size=2
            )
            second = ProcessedImage(
                full=b"f2", thumb=b"t2", sha256="22" * 32, byte_size=2
            )

            async def _upload(processed: ProcessedImage) -> None:
                async with maker() as session:
                    await NationService.replace_image(
                        session, nation_id, player_id, "flag", processed
                    )
                    await session.commit()

            await asyncio.gather(_upload(first), _upload(second))

            async with maker() as session:
                rows = (await session.execute(select(NationImage))).scalars().all()
            assert len(rows) == 1
            assert rows[0].sha256 in {first.sha256, second.sha256}
        finally:
            await engine.dispose()
